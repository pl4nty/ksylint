#!/usr/bin/env python3
"""Regenerate the rule table in README.md from the rule registry.

Usage:
    python scripts/gen_rule_table.py          # rewrite README.md
    python scripts/gen_rule_table.py --check  # exit 1 if README.md is stale
"""

from __future__ import annotations

import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from ksylint.registry import all_rules  # noqa: E402

START = "<!-- rules-table:start (generated by scripts/gen_rule_table.py) -->"
END = "<!-- rules-table:end -->"


def table() -> str:
    out = []
    current = None
    for r in all_rules():
        cat = r.category
        if cat != current:
            if current is not None:
                out.append("")
            out.append(f"#### {cat}")
            out.append("")
            out.append("| ID | Name | Severity | Fix | Description |")
            out.append("|----|------|----------|:---:|-------------|")
            current = cat
        desc = r.summary.replace("|", "\\|")
        if r.url:
            desc += f" ([style guide]({r.url}))"
        if not r.default_enabled:
            desc += " *Off by default.*"
        if r.options:
            opts = ", ".join(f"`{k}` (default `{v}`)" for k, v in r.options.items())
            desc += f" Options: {opts}."
        out.append(
            f"| `{r.id}` | `{r.name}` | {r.severity.value} | {'yes' if r.fixable else ''} | {desc} |"
        )
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    try:
        a = text.index(START) + len(START)
        b = text.index(END)
    except ValueError:
        print("README.md has no rule table markers", file=sys.stderr)
        return 2
    new = text[:a] + "\n\n" + table() + "\n\n" + text[b:]
    if args.check:
        if new != text:
            print(
                "README.md rule table is out of date; run scripts/gen_rule_table.py",
                file=sys.stderr,
            )
            return 1
        return 0
    readme.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
